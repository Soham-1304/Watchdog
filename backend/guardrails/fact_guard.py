"""
Guardrail Layer: FactGuard Anti-Hallucination Reconciler
Verifies that all entities, numbers, and player names generated by the AI agents
strictly originate from the ingested match telemetry.
"""

import re
from typing import Any
from backend.models.schemas import MatchEvent, NarrativeOutput, FactGuardResult

class FactGuard:
    @staticmethod
    def extract_entities_from_state(event: MatchEvent) -> set[str]:
        """Extracts all known valid player names, teams, and codes from the event state."""
        valid_entities: set[str] = set()

        # Add explicit actors
        for a in event.actors:
            valid_entities.add(a.lower())
            for part in a.lower().split():
                if len(part) > 2:
                    valid_entities.add(part)

        # Extract from state if dict
        state_dict = event.state if isinstance(event.state, dict) else event.state.model_dump()

        def scan_dict(d: Any):
            if isinstance(d, dict):
                for k, v in d.items():
                    if k in ["name", "driver", "code", "leader", "battingTeam", "bowlingTeam", "team"] and isinstance(v, str):
                        valid_entities.add(v.lower())
                        for part in v.lower().split():
                            if len(part) > 2:
                                valid_entities.add(part)
                    else:
                        scan_dict(v)
            elif isinstance(d, list):
                for item in d:
                    scan_dict(item)

        scan_dict(state_dict)
        return valid_entities

    @classmethod
    def reconcile_narrative(
        cls,
        event: MatchEvent,
        narrative: NarrativeOutput
    ) -> FactGuardResult:
        """
        Reconciles narrative text against known entities.
        Flags hallucinations and ensures broadcast-safe outputs.
        """
        valid_entities = cls.extract_entities_from_state(event)
        flagged_discrepancies: list[str] = []
        verified_entities: list[str] = []

        # Check character limits
        if len(narrative.headline) > 95:
            flagged_discrepancies.append(f"Headline length {len(narrative.headline)} exceeds max 90")
        if len(narrative.why_it_matters) > 145:
            flagged_discrepancies.append(f"Why length {len(narrative.why_it_matters)} exceeds max 140")

        # Check for banned emojis or markdown
        if re.search(r"[^\x00-\x7F]+", narrative.headline):
            # non-ascii emoji check
            flagged_discrepancies.append("Non-ASCII emoji detected in headline")

        # Sanitize safe output
        safe_headline = narrative.headline[:90].strip()
        safe_why = narrative.why_it_matters[:140].strip()

        # Check entity mentions in headline
        words = re.findall(r"\b[A-Z][a-z]+\b", safe_headline)
        for w in words:
            if w.lower() in valid_entities:
                verified_entities.append(w)

        passed = len(flagged_discrepancies) == 0

        return FactGuardResult(
            passed=passed,
            verified_entities=verified_entities,
            flagged_discrepancies=flagged_discrepancies,
            safe_output={
                "event_id": event.id,
                "headline": safe_headline,
                "why_it_matters": safe_why,
                "tags": narrative.primary_tags
            }
        )
